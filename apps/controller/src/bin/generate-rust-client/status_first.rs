//! Surface known HTTP rejection before reading a potentially stalled error body.
//! Checked against the pinned upstream template for every selected operation.

const RESPONSE_HEAD: &str = "        let response = req.send().await?;\n        let status = response.status();\n        let status_code = status.as_u16();\n        let headers = response.headers().clone();\n";

const STATUS_GUARD: &str = r#"        // Meshway acts on HTTP rejection immediately; error bodies are not consumed.
        if !status.is_success() {
            return Err(ApiOpError::Api(ApiError {
                status: status_code,
                headers,
                body: String::new(),
                raw_body: Vec::new(),
                typed: None,
                parse_error: None,
            }));
        }
"#;

const DOC_ADAPTATIONS: &[(&str, &str)] = &[
    (
        "/// Transport-level errors: failures where no safely inspectable\n/// HTTP response is available to the caller.\n///\n/// HTTP responses with non-2xx status codes are surfaced as\n/// [`ApiError`] inside [`ApiOpError::Api`], not here, so callers can\n/// always inspect status, headers, and the raw body when the server\n/// actually responded.",
        "/// Request/transport failures, including failures while reading a 2xx body.\n/// Non-2xx responses return [`ApiOpError::Api`] immediately with their status\n/// and headers; their bodies are never read or classified as transport failures.",
    ),
    (
        "/// Envelope returned for any HTTP response that we received but\n/// couldn't (or didn't) treat as a successful typed result.\n///\n/// Includes both non-2xx responses and 2xx responses whose body\n/// failed to deserialize into the expected success type. `status`,\n/// `headers`, and `raw_body` preserve what the server actually sent,\n/// while `body` is a convenient lossy UTF-8 rendering. `typed`\n/// carries the parsed per-operation error variant\n/// when the body matched a declared schema. Formatting the error\n/// limits only the displayed body preview; the public fields\n/// retain the complete response and parsing details.",
        "/// An HTTP rejection or a 2xx response that could not become a typed result.\n/// Status and headers are preserved. Meshway returns non-2xx responses before\n/// body I/O: `body` and `raw_body` are empty, `typed` and `parse_error` are `None`.\n/// Skipping an error body is not a deserialization failure. For 2xx decoding\n/// failures, the bounded body and parsing details are retained.",
    ),
    (
        "    /// Exact response bytes before lossy UTF-8 conversion.",
        "    /// Bounded 2xx response bytes; empty for non-2xx responses (body skipped).",
    ),
    (
        "    /// Servers generated by this tool always emit the problem\n    /// media type, so this succeeds against them.",
        "    /// Meshway skips non-2xx bodies, so their envelopes return `None`.",
    ),
    (
        "/// Result error type returned by every generated operation method.\n///\n/// `Transport` covers failures where we never got an inspectable\n/// response (network, timeout, middleware, request-side\n/// serialization). `Api` covers any case where the server *did*\n/// respond — the envelope always carries status + headers + raw\n/// body even when the typed deserialize fails.",
        "/// Result error type returned by every generated operation method.\n/// `Transport` covers request failures and failures reading a 2xx body. `Api`\n/// preserves status and headers for all non-2xx responses immediately, without\n/// reading their bodies, and for 2xx responses that fail typed decoding.",
    ),
];

pub fn adapt(source: &mut String, expected_operations: usize) -> Result<(), String> {
    if expected_operations == 0 {
        return Err("status-first adapter requires selected operations".into());
    }
    for (pattern, expected) in [
        ("let response = req.send().await?;", expected_operations),
        (RESPONSE_HEAD, expected_operations),
        (
            "let headers = response.headers().clone();",
            expected_operations,
        ),
        // Includes one helper definition in addition to the operation calls.
        ("__read_bounded_response_body(", expected_operations + 1),
    ] {
        let actual = source.matches(pattern).count();
        if actual != expected {
            return Err(format!(
                "upstream response template changed: expected {expected} occurrences, found {actual} for {pattern:?}; review status-first adapter"
            ));
        }
    }
    if source.contains(STATUS_GUARD) {
        return Err("status-first response guard already present".into());
    }
    for (before, _) in DOC_ADAPTATIONS {
        if source.matches(before).count() != 1 {
            return Err("upstream error documentation changed; review status-first adapter".into());
        }
    }
    // Validate the entire template before mutating it; never publish a partially
    // adapted client. The bounded reader and all 2xx decoding remain upstream's.
    *source = source.replace(RESPONSE_HEAD, &format!("{RESPONSE_HEAD}{STATUS_GUARD}"));
    for (before, after) in DOC_ADAPTATIONS {
        *source = source.replace(before, after);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use openapi_to_rust::{CodeGenerator, GeneratorConfig, SchemaAnalyzer};

    fn generated_client() -> String {
        let document = serde_json::from_str(&meshway_controller::openapi_json().unwrap()).unwrap();
        let mut analyzer = SchemaAnalyzer::new(document).unwrap();
        let mut analysis = analyzer.analyze().unwrap();
        let generator = CodeGenerator::new(GeneratorConfig {
            enable_async_client: true,
            enable_sse_client: false,
            tracing_enabled: false,
            client: Some(openapi_to_rust::config::ClientSection {
                operations: super::super::OPERATIONS
                    .into_iter()
                    .map(str::to_owned)
                    .collect(),
                prune_models: true,
            }),
            ..GeneratorConfig::default()
        });
        generator
            .generate_all(&mut analysis)
            .unwrap()
            .files
            .into_iter()
            .find(|file| file.path == std::path::Path::new("client.rs"))
            .unwrap()
            .content
    }

    #[test]
    fn all_selected_operations_reject_status_before_body_io() {
        let mut source = generated_client();
        let original = source.clone();
        let operations = super::super::OPERATIONS;
        assert!(operations.contains(&"getAgentDataplane"));
        assert!(operations.contains(&"getAgentDns"));
        adapt(&mut source, operations.len()).unwrap();
        assert_eq!(source.matches(STATUS_GUARD).count(), operations.len());
        assert!(source.contains("pub async fn get_agent_dataplane("));
        assert!(source.contains("pub async fn get_agent_dns("));
        // Every send is followed immediately by status extraction and the guard,
        // so no awaited reader can precede rejection within any operation.
        for operation in source.split(RESPONSE_HEAD).skip(1) {
            assert!(operation.starts_with(STATUS_GUARD));
            assert!(operation[STATUS_GUARD.len()..].contains("__read_bounded_response_body("));
        }
        // Removing only the adapter's additions recovers the entire upstream
        // body reader and success decoding byte-for-byte.
        let mut restored = source.replace(STATUS_GUARD, "");
        for (before, after) in DOC_ADAPTATIONS {
            assert_eq!(source.matches(after).count(), 1);
            restored = restored.replace(after, before);
        }
        assert_eq!(restored, original);
    }

    #[test]
    fn missing_extra_or_changed_operations_fail_without_partial_adaptation() {
        let original = generated_client();
        for mut source in [
            original.replacen(RESPONSE_HEAD, "", 1),
            format!("{original}{RESPONSE_HEAD}"),
            original.replacen(
                "let headers = response.headers().clone();",
                "let headers = response.headers().to_owned();",
                1,
            ),
            original.replacen(
                "let body_bytes = __read_bounded_response_body(",
                "let body_bytes = changed_body_reader(",
                1,
            ),
            original.replacen(
                "let response = req.send().await?;",
                "let response = req.send().await?;\n        consume_body().await?;",
                1,
            ),
            original.replacen(
                DOC_ADAPTATIONS[0].0,
                "/// changed upstream error documentation",
                1,
            ),
        ] {
            assert!(
                source != original,
                "fixture must change the upstream template"
            );
            let before = source.clone();
            assert!(adapt(&mut source, super::super::OPERATIONS.len()).is_err());
            assert_eq!(source, before);
        }
        let operation_count = super::super::OPERATIONS.len();
        for count in [0, operation_count - 1, operation_count + 1] {
            let mut source = original.clone();
            assert!(adapt(&mut source, count).is_err());
            assert_eq!(source, original);
        }
    }
}
