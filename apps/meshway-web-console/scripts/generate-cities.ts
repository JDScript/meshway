// Generates src/globe/cities.gen.ts: the principal cities of the IANA time
// zones, where the globe's night side lights up. Decorative only: it places
// no node.
//
// Source: IANA tz database 2026c, zone.tab (coordinates).
//   https://data.iana.org/time-zones/releases/tzdata2026c.tar.gz
//   sha256 e4a178a4477f3d0ea77cc31828ff72aa38feff8d61aa13e7e99e142e9d902be4
//
// Usage: node apps/meshway-web-console/scripts/generate-cities.ts <tzdata2026c.tar.gz>
import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"

const EXPECTED_SHA256 =
  "e4a178a4477f3d0ea77cc31828ff72aa38feff8d61aa13e7e99e142e9d902be4"

const archive = process.argv[2]
if (!archive) throw new Error("usage: generate-cities.ts <tzdata.tar.gz>")
const digest = createHash("sha256").update(readFileSync(archive)).digest("hex")
if (digest !== EXPECTED_SHA256)
  throw new Error(`unexpected source digest ${digest}`)

const work = mkdtempSync(join(tmpdir(), "tzdata-"))
let zoneTab: string
try {
  execFileSync("tar", ["xzf", archive, "-C", work, "zone.tab"])
  zoneTab = readFileSync(join(work, "zone.tab"), "utf8")
} finally {
  rmSync(work, { recursive: true, force: true })
}

/** ISO 6709 ±DDMM[SS]±DDDMM[SS], in degrees. */
function coordinates(text: string): [number, number] {
  const found =
    /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(text)
  if (!found) throw new Error(`bad coordinates ${text}`)
  const degrees = (sign = "+", d = "0", m = "0", s = "0") =>
    (sign === "-" ? -1 : 1) * (Number(d) + Number(m) / 60 + Number(s) / 3600)
  return [
    degrees(found[1], found[2], found[3], found[4]),
    degrees(found[5], found[6], found[7], found[8]),
  ]
}

const places: [number, number][] = []
for (const line of zoneTab.split("\n")) {
  if (line.startsWith("#") || line.trim() === "") continue
  const [, at] = line.split("\t")
  if (!at) throw new Error(`bad zone.tab line ${line}`)
  places.push(coordinates(at))
}

const round = (value: number) => Math.round(value * 10) / 10
const entries = places
  .map(([lat, lng]) => `${round(lat)},${round(lng)}`)
  .filter((entry, index, all) => all.indexOf(entry) === index)
  .sort()

writeFileSync(
  new URL("../src/globe/cities.gen.ts", import.meta.url),
  `// Generated by scripts/generate-cities.ts from the IANA tz database 2026c
// (zone.tab, sha256 ${EXPECTED_SHA256.slice(0, 16)}…). Do not edit.
// The time zones' principal cities, to 0.1°: where the night side lights up.

/** \`lat,lng\` entries, separated by \`;\`. */
export const CITIES = ${JSON.stringify(entries.join(";"))}
`
)
console.log(`${entries.length} cities`)
