// Generates src/lib/sky/time-zones.gen.ts: where each IANA time zone is (its
// principal city, as the tz database records it), so the console can place
// the reader roughly without asking for their location: the sunrise and
// sunset that follow the sun theme, and the sky behind the globe.
//
// Source: IANA tz database 2026c, zone.tab (coordinates) and backward
// (old names, which browsers may still report, linked to current ones).
//   https://data.iana.org/time-zones/releases/tzdata2026c.tar.gz
//   sha256 e4a178a4477f3d0ea77cc31828ff72aa38feff8d61aa13e7e99e142e9d902be4
//
// Usage: node apps/meshway-web-console/scripts/generate-time-zones.ts <tzdata2026c.tar.gz>
import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"

const EXPECTED_SHA256 =
  "e4a178a4477f3d0ea77cc31828ff72aa38feff8d61aa13e7e99e142e9d902be4"

const archive = process.argv[2]
if (!archive) throw new Error("usage: generate-time-zones.ts <tzdata.tar.gz>")
const digest = createHash("sha256").update(readFileSync(archive)).digest("hex")
if (digest !== EXPECTED_SHA256)
  throw new Error(`unexpected source digest ${digest}`)

const work = mkdtempSync(join(tmpdir(), "tzdata-"))
let zoneTab: string
let backward: string
try {
  execFileSync("tar", ["xzf", archive, "-C", work, "zone.tab", "backward"])
  zoneTab = readFileSync(join(work, "zone.tab"), "utf8")
  backward = readFileSync(join(work, "backward"), "utf8")
} finally {
  rmSync(work, { recursive: true, force: true })
}

/** ISO 6709 ±DDMM[SS]±DDDMM[SS], in degrees. */
function coordinates(text: string): [number, number] {
  const found =
    /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(text)
  if (!found) throw new Error(`bad coordinates ${text}`)
  const degrees = (sign = "+", d = "0", m = "0", s = "0") =>
    (sign === "-" ? -1 : 1) * (Number(d) + Number(m) / 60 + Number(s) / 3600)
  return [
    degrees(found[1], found[2], found[3], found[4]),
    degrees(found[5], found[6], found[7], found[8]),
  ]
}

const places = new Map<string, [number, number]>()
for (const line of zoneTab.split("\n")) {
  if (line.startsWith("#") || line.trim() === "") continue
  const [, at, zone] = line.split("\t")
  if (!at || !zone) throw new Error(`bad zone.tab line ${line}`)
  places.set(zone, coordinates(at))
}
for (const line of backward.split("\n")) {
  const found = /^Link\s+(\S+)\s+(\S+)/.exec(line)
  if (!found?.[1] || !found[2]) continue
  const place = places.get(found[1])
  if (place && !places.has(found[2])) places.set(found[2], place)
}

const round = (value: number) => Math.round(value * 10) / 10
const entries = [...places]
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([zone, [lat, lng]]) => `${zone}=${round(lat)},${round(lng)}`)

writeFileSync(
  new URL("../src/lib/sky/time-zones.gen.ts", import.meta.url),
  `// Generated by scripts/generate-time-zones.ts from the IANA tz database 2026c
// (zone.tab and backward, sha256 ${EXPECTED_SHA256.slice(0, 16)}…). Do not edit.
// Each zone's principal city, to 0.1°: a rough place, never the reader's own.

/** \`zone=lat,lng\` entries, separated by \`;\`. */
export const TIME_ZONES =
  ${JSON.stringify(entries.join(";"))}
`
)
console.log(`${entries.length} zones`)
