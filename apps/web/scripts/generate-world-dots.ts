// Generates lib/world-dots.gen.ts: a land / sea dot grid for the overview
// map backdrop. It is a decorative base layer only: no node is placed by it.
//
// Source: Natural Earth 1:110m Land (public domain), v5.1.2
//   https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson
//   sha256 9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9
//
// Usage: node apps/web/scripts/generate-world-dots.ts <ne_110m_land.geojson>
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const EXPECTED_SHA256 = "9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9"
// Equirectangular grid; Antarctica and the far north are left out.
const STEP = 1.5
const NORTH = 82.5
const SOUTH = -57
const WEST = -180
const EAST = 180

type Ring = [number, number][]
type Polygon = Ring[]

const path = process.argv[2]
if (!path) throw new Error("usage: generate-world-dots.ts <ne_110m_land.geojson>")
const raw = readFileSync(path)
const digest = createHash("sha256").update(raw).digest("hex")
if (digest !== EXPECTED_SHA256) throw new Error(`unexpected source digest ${digest}`)

const parsed: unknown = JSON.parse(raw.toString("utf8"))
function isRing(value: unknown): value is Ring {
  return Array.isArray(value) && value.every((point) => Array.isArray(point) && typeof point[0] === "number" && typeof point[1] === "number")
}
function polygonsOf(geometry: unknown): Polygon[] {
  if (typeof geometry !== "object" || geometry === null || !("type" in geometry) || !("coordinates" in geometry)) return []
  const coordinates: unknown = geometry.coordinates
  if (!Array.isArray(coordinates)) return []
  if (geometry.type === "Polygon") return coordinates.every(isRing) ? [coordinates] : []
  if (geometry.type === "MultiPolygon") return coordinates.filter((polygon): polygon is Polygon => Array.isArray(polygon) && polygon.every(isRing))
  return []
}
if (typeof parsed !== "object" || parsed === null || !("features" in parsed) || !Array.isArray(parsed.features)) throw new Error("not a FeatureCollection")
const polygons: Polygon[] = parsed.features.flatMap((feature: unknown) =>
  typeof feature === "object" && feature !== null && "geometry" in feature ? polygonsOf(feature.geometry) : []
)

function inRing(lon: number, lat: number, ring: Ring): boolean {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const a = ring[i]
    const b = ring[j]
    if (!a || !b) continue
    const [xi, yi] = a
    const [xj, yj] = b
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}
const isLand = (lon: number, lat: number) =>
  polygons.some(([outer, ...holes]) => outer !== undefined && inRing(lon, lat, outer) && !holes.some((hole) => inRing(lon, lat, hole)))

const rows: string[] = []
for (let lat = NORTH; lat >= SOUTH; lat -= STEP) {
  let row = ""
  for (let lon = WEST + STEP / 2; lon < EAST; lon += STEP) row += isLand(lon, lat) ? "1" : "0"
  rows.push(row)
}

const out = `// Generated by scripts/generate-world-dots.ts from Natural Earth 1:110m Land
// (public domain, v5.1.2, sha256 ${EXPECTED_SHA256.slice(0, 16)}…). Do not edit.
// Decorative backdrop only: it places no node.

export const WORLD_DOTS = {
  step: ${STEP},
  north: ${NORTH},
  west: ${WEST},
  /** One string per latitude row from north to south; "1" is land. */
  rows: [
${rows.map((row) => `    "${row}",`).join("\n")}
  ],
} as const
`
writeFileSync(join(import.meta.dirname, "..", "lib", "world-dots.gen.ts"), out)
console.log(`rows ${rows.length} × ${rows[0]?.length ?? 0}, land ${rows.join("").split("1").length - 1}`)
